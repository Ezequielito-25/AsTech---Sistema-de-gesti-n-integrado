"""Datos del presupuesto mensual. Usa la misma base astech.db que la tienda (tablas con prefijo pres_)."""
import calendar
from datetime import date

import pandas as pd

from db import conectar

CATEGORIAS = ["Necesidad", "Deseo", "Ahorro"]

# nombre lógico -> (tabla real, columnas sin id, anio ni mes)
TABLAS = {
    "ingresos": ("pres_ingresos", ["concepto", "dia", "monto"]),
    "fijos": ("pres_fijos", ["concepto", "vence_dia", "monto"]),
    "suscripciones": ("pres_suscripciones", ["servicio", "cobra_dia", "monto"]),
}


def crear_tablas():
    con = conectar()
    con.execute("""
        CREATE TABLE IF NOT EXISTS pres_meses (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            anio INTEGER NOT NULL,
            mes INTEGER NOT NULL,
            objetivo TEXT,
            ahorro_pct DOUBLE PRECISION NOT NULL DEFAULT 0.15,
            pct_necesidades DOUBLE PRECISION NOT NULL DEFAULT 0.5,
            pct_deseos DOUBLE PRECISION NOT NULL DEFAULT 0.3,
            pct_ahorro_extra DOUBLE PRECISION NOT NULL DEFAULT 0.2,
            UNIQUE (anio, mes)
        );
        CREATE TABLE IF NOT EXISTS pres_ingresos (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            anio INTEGER NOT NULL,
            mes INTEGER NOT NULL,
            concepto TEXT NOT NULL,
            dia INTEGER,
            monto DOUBLE PRECISION NOT NULL DEFAULT 0
        );
        CREATE TABLE IF NOT EXISTS pres_fijos (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            anio INTEGER NOT NULL,
            mes INTEGER NOT NULL,
            concepto TEXT NOT NULL,
            vence_dia INTEGER,
            monto DOUBLE PRECISION NOT NULL DEFAULT 0
        );
        CREATE TABLE IF NOT EXISTS pres_suscripciones (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            anio INTEGER NOT NULL,
            mes INTEGER NOT NULL,
            servicio TEXT NOT NULL,
            cobra_dia INTEGER,
            monto DOUBLE PRECISION NOT NULL DEFAULT 0
        );
        -- Gastos del día a día: se guardan por fecha
        CREATE TABLE IF NOT EXISTS pres_gastos (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            fecha TEXT NOT NULL,
            concepto TEXT NOT NULL,
            categoria TEXT NOT NULL CHECK (categoria IN ('Necesidad', 'Deseo', 'Ahorro')),
            monto DOUBLE PRECISION NOT NULL DEFAULT 0
        );
    """)
    con.commit()
    con.close()


def rango_mes(anio, mes):
    ultimo = calendar.monthrange(anio, mes)[1]
    return date(anio, mes, 1), date(anio, mes, ultimo)


def _mes_anterior(anio, mes):
    return (anio - 1, 12) if mes == 1 else (anio, mes - 1)


# ---------------------------------------------------------------- CONFIGURACIÓN DEL MES
def obtener_config(anio, mes):
    con = conectar()
    fila = con.execute("SELECT * FROM pres_meses WHERE anio = ? AND mes = ?", (anio, mes)).fetchone()
    if fila is None:
        con.execute("INSERT INTO pres_meses (anio, mes) VALUES (?, ?)", (anio, mes))
        con.commit()
        fila = con.execute("SELECT * FROM pres_meses WHERE anio = ? AND mes = ?", (anio, mes)).fetchone()
    con.close()
    return dict(fila)


def guardar_config(anio, mes, objetivo, ahorro_pct, pct_nec, pct_des, pct_aho):
    obtener_config(anio, mes)
    con = conectar()
    con.execute(
        """UPDATE pres_meses SET objetivo = ?, ahorro_pct = ?, pct_necesidades = ?,
           pct_deseos = ?, pct_ahorro_extra = ? WHERE anio = ? AND mes = ?""",
        (objetivo, ahorro_pct, pct_nec, pct_des, pct_aho, anio, mes),
    )
    con.commit()
    con.close()


# ---------------------------------------------------------------- TABLAS MENSUALES
def listar_df(tabla, anio, mes):
    sql_tabla, cols = TABLAS[tabla]
    con = conectar()
    filas = con.execute(
        f"SELECT {', '.join(cols)} FROM {sql_tabla} WHERE anio = ? AND mes = ? ORDER BY id",
        (anio, mes),
    ).fetchall()
    con.close()
    return pd.DataFrame([tuple(f[c] for c in cols) for f in filas], columns=cols)


def reemplazar_tabla(tabla, anio, mes, df):
    sql_tabla, cols = TABLAS[tabla]
    con = conectar()
    con.execute(f"DELETE FROM {sql_tabla} WHERE anio = ? AND mes = ?", (anio, mes))
    marcadores = ", ".join("?" * len(cols))
    for _, fila in df.iterrows():
        nombre = fila[cols[0]]
        if pd.isna(nombre) or not str(nombre).strip():
            continue
        valores = [str(nombre).strip()]
        for c in cols[1:]:
            v = fila[c]
            if pd.isna(v):
                valores.append(None)
            else:
                valores.append(float(v) if c == "monto" else int(v))
        con.execute(
            f"INSERT INTO {sql_tabla} (anio, mes, {', '.join(cols)}) VALUES (?, ?, {marcadores})",
            (anio, mes, *valores),
        )
    con.commit()
    con.close()


def copiar_recurrentes(anio, mes):
    """Copia fijos y suscripciones del mes anterior, solo si el mes actual todavía no tiene ninguno."""
    pa, pm = _mes_anterior(anio, mes)
    con = conectar()
    for tabla in ("fijos", "suscripciones"):
        sql_tabla, cols = TABLAS[tabla]
        ya = con.execute(f"SELECT COUNT(*) AS n FROM {sql_tabla} WHERE anio = ? AND mes = ?", (anio, mes)).fetchone()["n"]
        if ya:
            continue
        lista = ", ".join(cols)
        con.execute(
            f"INSERT INTO {sql_tabla} (anio, mes, {lista}) SELECT ?, ?, {lista} FROM {sql_tabla} WHERE anio = ? AND mes = ?",
            (anio, mes, pa, pm),
        )
    con.commit()
    con.close()


# ---------------------------------------------------------------- GASTOS DEL DÍA A DÍA
def listar_gastos_df(anio, mes):
    desde, hasta = rango_mes(anio, mes)
    con = conectar()
    filas = con.execute(
        "SELECT fecha, concepto, categoria, monto FROM pres_gastos WHERE fecha BETWEEN ? AND ? ORDER BY fecha, id",
        (desde.isoformat(), hasta.isoformat()),
    ).fetchall()
    con.close()
    df = pd.DataFrame([tuple(f[c] for c in ["fecha", "concepto", "categoria", "monto"]) for f in filas],
                      columns=["fecha", "concepto", "categoria", "monto"])
    if not df.empty:
        df["fecha"] = df["fecha"].map(date.fromisoformat)
    return df


def reemplazar_gastos(anio, mes, df):
    """Guarda los gastos del mes. Devuelve cuántos tenían fecha fuera del mes (no se guardan)."""
    desde, hasta = rango_mes(anio, mes)
    con = conectar()
    con.execute("DELETE FROM pres_gastos WHERE fecha BETWEEN ? AND ?", (desde.isoformat(), hasta.isoformat()))
    omitidos = 0
    for _, fila in df.iterrows():
        fecha, concepto = fila["fecha"], fila["concepto"]
        categoria, monto = fila["categoria"], fila["monto"]
        if pd.isna(fecha) or pd.isna(concepto) or not str(concepto).strip():
            continue
        if categoria not in CATEGORIAS:
            continue
        f = pd.to_datetime(fecha).date()
        if not (desde <= f <= hasta):
            omitidos += 1
            continue
        con.execute(
            "INSERT INTO pres_gastos (fecha, concepto, categoria, monto) VALUES (?, ?, ?, ?)",
            (f.isoformat(), str(concepto).strip(), categoria, 0.0 if pd.isna(monto) else float(monto)),
        )
    con.commit()
    con.close()
    return omitidos


# ---------------------------------------------------------------- RESUMEN (las cuentas de la planilla)
def resumen_mes(anio, mes):
    cfg = obtener_config(anio, mes)
    ingresos = float(listar_df("ingresos", anio, mes)["monto"].sum())
    fijos = float(listar_df("fijos", anio, mes)["monto"].sum())
    subs = float(listar_df("suscripciones", anio, mes)["monto"].sum())

    ahorro = round(ingresos * cfg["ahorro_pct"])
    comprometido = ahorro + fijos + subs
    libre = ingresos - comprometido

    libre_pos = max(0, libre)
    presupuesto = {
        "Necesidad": round(libre_pos * cfg["pct_necesidades"]),
        "Deseo": round(libre_pos * cfg["pct_deseos"]),
        "Ahorro": round(libre_pos * cfg["pct_ahorro_extra"]),
    }

    gastos = listar_gastos_df(anio, mes)
    gastado = {c: 0.0 for c in CATEGORIAS}
    if not gastos.empty:
        for cat, total in gastos.groupby("categoria")["monto"].sum().items():
            gastado[cat] = float(total)
    total_gastado = sum(gastado.values())

    return {
        "cfg": cfg,
        "ingresos": ingresos,
        "ahorro": ahorro,
        "fijos": fijos,
        "subs": subs,
        "comprometido": comprometido,
        "libre": libre,
        "presupuesto": presupuesto,
        "gastado": gastado,
        "total_gastado": total_gastado,
        "quedo": ingresos - comprometido - total_gastado,
    }
