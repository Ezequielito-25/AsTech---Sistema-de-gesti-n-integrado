"""Datos del apartado Amway. Tabla propia (prefijo amway_), separada de los clientes de la tienda."""
import re
import psycopg
import unicodedata
from datetime import datetime

import pandas as pd

from db import conectar

COLUMNAS = ["numero", "nombre", "telefono", "direccion", "fecha", "descripcion", "valor", "puntos"]


def crear_tablas():
    con = conectar()
    con.execute("""
        -- Cada fila es una compra. tipo = 'cliente' (solo compra) o 'asociado' (se sumó al equipo)
        CREATE TABLE IF NOT EXISTS amway_registros (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tipo TEXT NOT NULL CHECK (tipo IN ('cliente', 'asociado')),
            anio INTEGER NOT NULL,
            mes INTEGER NOT NULL,
            numero INTEGER,
            nombre TEXT NOT NULL,
            telefono TEXT,
            direccion TEXT,
            fecha TEXT,
            descripcion TEXT,
            valor DOUBLE PRECISION NOT NULL DEFAULT 0,
            puntos DOUBLE PRECISION NOT NULL DEFAULT 0
        );
        -- Ficha de cada asociado (datos personales). Se vincula con sus compras por teléfono.
        CREATE TABLE IF NOT EXISTS amway_asociados (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nombre TEXT NOT NULL,
            telefono TEXT,
            email TEXT,
            direccion TEXT,
            fecha_alta TEXT NOT NULL,
            patrocinador TEXT,
            notas TEXT,
            creado TEXT NOT NULL
        );
        -- Catálogo de productos Amway que carga el usuario a mano
        CREATE TABLE IF NOT EXISTS amway_productos (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nombre TEXT NOT NULL,
            descripcion TEXT,
            beneficios TEXT,
            creado TEXT NOT NULL
        );
    """)
    # Migración: columnas nuevas del catálogo (si la base ya existía)
    con.execute("""
        ALTER TABLE amway_productos ADD COLUMN IF NOT EXISTS categoria TEXT;
        ALTER TABLE amway_productos ADD COLUMN IF NOT EXISTS codigo_sitio TEXT;
        ALTER TABLE amway_productos ADD COLUMN IF NOT EXISTS precio_cliente DOUBLE PRECISION;
        ALTER TABLE amway_productos ADD COLUMN IF NOT EXISTS precio_empresario DOUBLE PRECISION;
        CREATE UNIQUE INDEX IF NOT EXISTS amway_productos_nombre_uq ON amway_productos (lower(nombre));
    """)
    con.commit()
    con.close()


def _normalizar(texto):
    texto = unicodedata.normalize("NFD", str(texto or ""))
    return "".join(c for c in texto if unicodedata.category(c) != "Mn").lower()


def _txt(valor):
    if valor is None or pd.isna(valor):
        return None
    return str(valor).strip() or None


def _num(valor):
    if valor is None or pd.isna(valor):
        return 0.0
    return float(valor)


def listar(tipo, anio, mes):
    """Compras de un mes para 'cliente' o 'asociado', tal como se muestran en la planilla."""
    con = conectar()
    filas = con.execute(
        """SELECT numero, nombre, telefono, direccion, fecha, descripcion, valor, puntos
           FROM amway_registros WHERE tipo = ? AND anio = ? AND mes = ? ORDER BY numero, id""",
        (tipo, anio, mes),
    ).fetchall()
    con.close()
    df = pd.DataFrame([tuple(f[c] for c in COLUMNAS) for f in filas], columns=COLUMNAS)
    if not df.empty:
        df["fecha"] = df["fecha"].map(lambda s: pd.to_datetime(s).date() if s else None)
    return df


def reemplazar(tipo, anio, mes, df):
    """Guarda la tabla del mes tal como quedó en pantalla. La numeración (N°) se recalcula sola."""
    con = conectar()
    con.execute("DELETE FROM amway_registros WHERE tipo = ? AND anio = ? AND mes = ?", (tipo, anio, mes))
    n = 0
    for fila in df.itertuples(index=False):
        nombre = _txt(fila.nombre)
        if not nombre:
            continue
        n += 1
        fecha = None if pd.isna(fila.fecha) else pd.to_datetime(fila.fecha).date().isoformat()
        con.execute(
            """INSERT INTO amway_registros
               (tipo, anio, mes, numero, nombre, telefono, direccion, fecha, descripcion, valor, puntos)
               VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
            (tipo, anio, mes, n, nombre, _txt(fila.telefono), _txt(fila.direccion), fecha,
             _txt(fila.descripcion), _num(fila.valor), _num(fila.puntos)),
        )
    con.commit()
    con.close()


def nombres_productos_amway():
    con = conectar()
    filas = con.execute("SELECT nombre FROM amway_productos ORDER BY lower(nombre)").fetchall()
    con.close()
    return [f["nombre"] for f in filas]


def listar_productos_amway(texto=""):
    con = conectar()
    filas = con.execute("SELECT * FROM amway_productos ORDER BY lower(nombre)").fetchall()
    con.close()
    productos = [dict(f) for f in filas]
    buscado = _normalizar((texto or "").strip())
    if not buscado:
        return productos
    return [p for p in productos
            if buscado in _normalizar(p["nombre"]) or buscado in _normalizar(p["descripcion"])
            or buscado in _normalizar(p["beneficios"])]


def agregar_producto_amway(nombre, descripcion, beneficios, categoria=None, codigo_sitio=None,
                           precio_cliente=None, precio_empresario=None):
    """Devuelve False si ya existe un producto con ese nombre."""
    con = conectar()
    try:
        con.execute(
            "INSERT INTO amway_productos (nombre, descripcion, beneficios, creado, categoria, codigo_sitio, "
            "precio_cliente, precio_empresario) VALUES (?,?,?,?,?,?,?,?)",
            (nombre.strip(), _txt(descripcion), _txt(beneficios), datetime.now().isoformat(timespec="seconds"),
             _txt(categoria), _txt(codigo_sitio), _num(precio_cliente), _num(precio_empresario)),
        )
        con.commit()
        return True
    except psycopg.IntegrityError:
        return False
    finally:
        con.close()


def actualizar_producto_amway(producto_id, nombre, descripcion, beneficios,
                              precio_cliente=None, precio_empresario=None):
    con = conectar()
    try:
        con.execute(
            "UPDATE amway_productos SET nombre = ?, descripcion = ?, beneficios = ?, "
            "precio_cliente = ?, precio_empresario = ? WHERE id = ?",
            (nombre.strip(), _txt(descripcion), _txt(beneficios),
             _num(precio_cliente), _num(precio_empresario), producto_id),
        )
        con.commit()
        return True
    except psycopg.IntegrityError:
        return False
    finally:
        con.close()


def importar_catalogo_web(items):
    """Carga los productos que todavía no están en el catálogo. Devuelve (cantidad_cargada, nombres_omitidos)."""
    existentes = {_normalizar(n) for n in nombres_productos_amway()}
    cargados, omitidos = 0, []
    for it in items:
        if _normalizar(it["nombre"]) in existentes:
            omitidos.append(it["nombre"])
            continue
        beneficios = "\n".join(f"- {b}" for b in it.get("beneficios", [])) or None
        if agregar_producto_amway(it["nombre"], it.get("descripcion"), beneficios,
                                  categoria=it.get("categoria"), codigo_sitio=it.get("codigo"),
                                  precio_cliente=it.get("precio_cliente")):
            cargados += 1
            existentes.add(_normalizar(it["nombre"]))
    return cargados, omitidos


def eliminar_producto_amway(producto_id):
    """Quita el producto del catálogo. Las compras ya cargadas conservan el nombre que tenían."""
    con = conectar()
    con.execute("DELETE FROM amway_productos WHERE id = ?", (producto_id,))
    con.commit()
    con.close()


def _digitos(texto):
    return re.sub(r"\D", "", str(texto or ""))


def alta_asociado(nombre, telefono, email, direccion, fecha_alta, patrocinador, notas,
                  valor=0.0, puntos=0.0, producto=None):
    """Registra un asociado con sus datos personales y, a la vez, su fila en la tabla del mes del alta."""
    con = conectar()
    cur = con.execute(
        """INSERT INTO amway_asociados (nombre, telefono, email, direccion, fecha_alta,
           patrocinador, notas, creado) VALUES (?,?,?,?,?,?,?,?) RETURNING id""",
        (nombre.strip(), _txt(telefono), _txt(email), _txt(direccion), fecha_alta.isoformat(),
         _txt(patrocinador), _txt(notas), datetime.now().isoformat(timespec="seconds")),
    )
    asociado_id = cur.fetchone()["id"]
    numero = con.execute(
        "SELECT COALESCE(MAX(numero), 0) + 1 AS n FROM amway_registros WHERE tipo = 'asociado' AND anio = ? AND mes = ?",
        (fecha_alta.year, fecha_alta.month),
    ).fetchone()["n"]
    con.execute(
        """INSERT INTO amway_registros
           (tipo, anio, mes, numero, nombre, telefono, direccion, fecha, descripcion, valor, puntos)
           VALUES ('asociado', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        (fecha_alta.year, fecha_alta.month, numero, nombre.strip(), _txt(telefono), _txt(direccion),
         fecha_alta.isoformat(), producto or "Alta en el equipo", _num(valor), _num(puntos)),
    )
    con.commit()
    con.close()
    return asociado_id


def listar_asociados():
    con = conectar()
    filas = con.execute("SELECT * FROM amway_asociados ORDER BY fecha_alta DESC, id DESC").fetchall()
    con.close()
    return [dict(f) for f in filas]


def buscar_asociados(texto):
    """Filtra las fichas por nombre (sin acentos) o por teléfono."""
    todos = listar_asociados()
    texto = (texto or "").strip()
    if not texto:
        return todos
    buscado = _normalizar(texto)
    digitos = _digitos(texto)
    return [a for a in todos
            if buscado in _normalizar(a["nombre"]) or (digitos and digitos in _digitos(a["telefono"]))]


def actualizar_asociado(asociado_id, nombre, telefono, email, direccion, patrocinador, notas, fecha_alta):
    con = conectar()
    anterior = con.execute("SELECT telefono FROM amway_asociados WHERE id = ?", (asociado_id,)).fetchone()
    con.execute(
        """UPDATE amway_asociados SET nombre = ?, telefono = ?, email = ?, direccion = ?,
           patrocinador = ?, notas = ?, fecha_alta = ? WHERE id = ?""",
        (nombre.strip(), _txt(telefono), _txt(email), _txt(direccion), _txt(patrocinador),
         _txt(notas), fecha_alta.isoformat(), asociado_id),
    )
    # Mantiene sincronizadas las compras de la tabla mensual (misma persona = mismo teléfono)
    tel_viejo = _digitos(anterior["telefono"]) if anterior else ""
    if tel_viejo:
        filas = con.execute("SELECT id, telefono FROM amway_registros WHERE tipo = 'asociado'").fetchall()
        for f in filas:
            if _digitos(f["telefono"]) == tel_viejo:
                con.execute("UPDATE amway_registros SET nombre = ?, telefono = ?, direccion = ? WHERE id = ?",
                            (nombre.strip(), _txt(telefono), _txt(direccion), f["id"]))
    con.commit()
    con.close()


def importar_asociados_existentes():
    """Crea la ficha de cada asociado que ya figura en las tablas mensuales y todavía no tiene ficha."""
    personas = buscar_personas("asociado", "")
    fichas = listar_asociados()
    tels = {_digitos(a["telefono"]) for a in fichas if a["telefono"]}
    nombres = {_normalizar(a["nombre"]) for a in fichas}
    hoy = datetime.now().date().isoformat()
    creados = 0
    con = conectar()
    for g in personas:
        tel = _digitos(g["telefono"])
        if (tel and tel in tels) or (not tel and _normalizar(g["nombre"]) in nombres):
            continue
        fechas = [c["fecha"] for c in g["compras"] if c["fecha"]]
        alta = min(fechas) if fechas else hoy
        con.execute(
            """INSERT INTO amway_asociados (nombre, telefono, email, direccion, fecha_alta,
               patrocinador, notas, creado) VALUES (?,?,?,?,?,?,?,?)""",
            (g["nombre"], _txt(g["telefono"]), None, _txt(g["direccion"]), alta, None, None,
             datetime.now().isoformat(timespec="seconds")),
        )
        creados += 1
    con.commit()
    con.close()
    return creados


def totales(tipo, anio, mes):
    df = listar(tipo, anio, mes)
    return {
        "filas": len(df),
        "ventas": float(df["valor"].sum()) if not df.empty else 0.0,
        "puntos": float(df["puntos"].sum()) if not df.empty else 0.0,
    }


def resumen_anio(anio):
    filas = []
    for m in range(1, 13):
        c = totales("cliente", anio, m)
        a = totales("asociado", anio, m)
        filas.append({"mes": m, "ventas_clientes": c["ventas"], "puntos_clientes": c["puntos"],
                      "ventas_asociados": a["ventas"], "puntos_asociados": a["puntos"]})
    return filas


def buscar_personas(tipo, texto):
    """Agrupa las compras por persona (teléfono, o nombre si no tiene teléfono) y filtra por nombre o número."""
    con = conectar()
    filas = con.execute(
        """SELECT id, anio, mes, nombre, telefono, direccion, fecha, descripcion, valor, puntos
           FROM amway_registros WHERE tipo = ? ORDER BY anio, mes, fecha, id""",
        (tipo,),
    ).fetchall()
    con.close()

    grupos = {}
    for f in filas:
        clave = re.sub(r"\D", "", f["telefono"] or "") or _normalizar(f["nombre"])
        g = grupos.setdefault(clave, {"nombre": f["nombre"], "telefono": f["telefono"],
                                      "direccion": f["direccion"], "compras": [], "nombres": set()})
        g["nombres"].add(f["nombre"])
        g["nombre"] = f["nombre"]
        g["telefono"] = f["telefono"] or g["telefono"]
        g["direccion"] = f["direccion"] or g["direccion"]
        g["compras"].append(dict(f))

    buscado = _normalizar((texto or "").strip())
    digitos = re.sub(r"\D", "", texto or "")
    resultado = []
    for g in grupos.values():
        por_nombre = bool(buscado) and any(buscado in _normalizar(n) for n in g["nombres"])
        por_numero = bool(digitos) and digitos in re.sub(r"\D", "", g["telefono"] or "")
        if not buscado and not digitos or por_nombre or por_numero:
            g["total_valor"] = sum(c["valor"] for c in g["compras"])
            g["total_puntos"] = sum(c["puntos"] for c in g["compras"])
            resultado.append(g)
    return sorted(resultado, key=lambda g: _normalizar(g["nombre"]))


def actualizar_compra(registro_id, fecha, descripcion, valor, puntos):
    """Corrige una compra puntual: fecha, descripción, valor o puntos."""
    con = conectar()
    con.execute(
        "UPDATE amway_registros SET fecha = ?, descripcion = ?, valor = ?, puntos = ? WHERE id = ?",
        (fecha.isoformat() if fecha else None, descripcion or None, float(valor), float(puntos), registro_id),
    )
    con.commit()
    con.close()


def actualizar_persona(ids, nombre, telefono, direccion):
    """Corrige nombre, teléfono o dirección en todas las compras de una persona (por si hay una letra mal)."""
    con = conectar()
    marcas = ",".join("?" * len(ids))
    con.execute(
        f"UPDATE amway_registros SET nombre = ?, telefono = ?, direccion = ? WHERE id IN ({marcas})",
        (nombre.strip(), telefono.strip() or None, direccion.strip() or None, *ids),
    )
    con.commit()
    con.close()


