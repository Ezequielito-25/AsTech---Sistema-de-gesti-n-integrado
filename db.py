"""Base de datos de AsTech (PostgreSQL en Supabase). Todas las funciones de acceso a datos viven aquí.

La conexión sale de la variable de entorno DATABASE_URL o de los secretos de Streamlit ([db] url = "...").
"""
import json
import os
import re
import unicodedata
from datetime import date, datetime

import pandas as pd
import psycopg
from psycopg.rows import dict_row


def _cadena_conexion():
    url = os.environ.get("DATABASE_URL")
    if not url:
        try:
            import streamlit as st
            url = st.secrets["db"]["url"]
        except Exception:
            url = None
    if not url:
        raise RuntimeError('Falta la cadena de conexión a la base: cargala en los secretos como [db] url = "..."')
    return url


class _Conexion:
    """Envoltorio fino sobre psycopg: acepta '?' como marcador (como en SQLite) y devuelve filas tipo dict."""

    def __init__(self):
        self._c = psycopg.connect(_cadena_conexion(), row_factory=dict_row)

    def execute(self, sql, params=None):
        return self._c.execute(sql.replace("?", "%s"), params or None)

    def commit(self):
        self._c.commit()

    def rollback(self):
        self._c.rollback()

    def close(self):
        self._c.close()


def conectar():
    return _Conexion()


def crear_tablas():
    con = conectar()
    con.execute("""
        CREATE TABLE IF NOT EXISTS productos (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            descripcion TEXT NOT NULL,
            precio_ars DOUBLE PRECISION NOT NULL DEFAULT 0,
            precio_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
            imagen TEXT,
            creado TEXT NOT NULL,
            numero_serie TEXT
        );
        CREATE TABLE IF NOT EXISTS clientes (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nombre TEXT NOT NULL,
            telefono_wp TEXT,
            email TEXT,
            direccion TEXT,
            creado TEXT NOT NULL
        );
        -- Operaciones: tipo = 'venta' (producto) o 'reparacion' (servicio técnico)
        CREATE TABLE IF NOT EXISTS operaciones (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tipo TEXT NOT NULL CHECK (tipo IN ('venta', 'reparacion')),
            cliente_id INTEGER NOT NULL REFERENCES clientes(id),
            fecha TEXT NOT NULL,
            descripcion TEXT,
            monto_ars DOUBLE PRECISION NOT NULL DEFAULT 0,
            monto_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
            pagado_ars DOUBLE PRECISION NOT NULL DEFAULT 0,
            pagado_usd DOUBLE PRECISION NOT NULL DEFAULT 0
        );
        -- Renglones de una venta (qué productos se vendieron)
        CREATE TABLE IF NOT EXISTS operacion_items (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            operacion_id INTEGER NOT NULL REFERENCES operaciones(id) ON DELETE CASCADE,
            producto_id INTEGER REFERENCES productos(id),
            descripcion TEXT NOT NULL,
            cantidad INTEGER NOT NULL DEFAULT 1,
            precio_ars DOUBLE PRECISION NOT NULL DEFAULT 0,
            precio_usd DOUBLE PRECISION NOT NULL DEFAULT 0
        );
        -- Fotos de productos (se guardan en la base para que funcionen desde la nube)
        CREATE TABLE IF NOT EXISTS imagenes (
            nombre TEXT PRIMARY KEY,
            datos BYTEA NOT NULL
        );
        -- Copia de seguridad de cada cliente borrado (reemplaza la copia del archivo .db)
        CREATE TABLE IF NOT EXISTS clientes_eliminados (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cliente_id INTEGER NOT NULL,
            nombre TEXT,
            datos TEXT NOT NULL,
            borrado_en TEXT NOT NULL
        );
    """)
    con.commit()
    con.close()


# ---------------------------------------------------------------- IMÁGENES
def guardar_imagen_bytes(nombre, datos):
    """Guarda (o reemplaza) una imagen con ese nombre y devuelve el nombre."""
    con = conectar()
    con.execute(
        """INSERT INTO imagenes (nombre, datos) VALUES (?,?)
           ON CONFLICT (nombre) DO UPDATE SET datos = EXCLUDED.datos""",
        (nombre, psycopg.Binary(datos)),
    )
    con.commit()
    con.close()
    return nombre


def guardar_imagen(archivo):
    """Guarda un archivo subido desde la app y devuelve el nombre con el que quedó guardado."""
    if archivo is None:
        return None
    nombre = f"{datetime.now():%Y%m%d%H%M%S}_{archivo.name}"
    return guardar_imagen_bytes(nombre, bytes(archivo.getbuffer()))


def leer_imagen(nombre):
    """Devuelve los bytes de la imagen, o None si no existe."""
    if not nombre:
        return None
    con = conectar()
    fila = con.execute("SELECT datos FROM imagenes WHERE nombre = ?", (nombre,)).fetchone()
    con.close()
    return bytes(fila["datos"]) if fila else None


