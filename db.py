def ventas_de_producto(producto_id):
    """Historial: a qué cliente y en qué fecha se vendió este producto."""
    con = conectar()
    filas = con.execute(
        """SELECT o.fecha, c.nombre AS cliente, c.telefono_wp, i.cantidad,
                  i.precio_ars, i.precio_usd
           FROM operacion_items i
           JOIN operaciones o ON o.id = i.operacion_id
           JOIN clientes c ON c.id = o.cliente_id
           WHERE i.producto_id = ?
           ORDER BY o.fecha DESC, o.id DESC""",
        (producto_id,),
    ).fetchall()
    con.close()
    return [dict(f) for f in filas]


