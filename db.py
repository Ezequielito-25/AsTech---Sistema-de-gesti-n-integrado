COLUMNAS_OPERACIONES = ["id", "tipo", "fecha", "cliente", "telefono_wp", "descripcion",
                        "monto_ars", "monto_usd", "pagado_ars", "pagado_usd", "deuda_ars", "deuda_usd"]


def listar_operaciones(desde=None, hasta=None):
    """Devuelve operaciones con datos del cliente y saldo pendiente, en un DataFrame."""
    sql = """
        SELECT o.id, o.tipo, o.fecha, c.nombre AS cliente, c.telefono_wp,
               o.descripcion, o.monto_ars, o.monto_usd, o.pagado_ars, o.pagado_usd,
               (o.monto_ars - o.pagado_ars) AS deuda_ars,
               (o.monto_usd - o.pagado_usd) AS deuda_usd
        FROM operaciones o JOIN clientes c ON c.id = o.cliente_id
        WHERE 1=1
    """
    params = []
    if desde:
        sql += " AND o.fecha >= ?"
        params.append(desde.isoformat())
    if hasta:
        sql += " AND o.fecha <= ?"
        params.append(hasta.isoformat())
    sql += " ORDER BY o.fecha DESC, o.id DESC"
    con = conectar()
    filas = con.execute(sql, params).fetchall()
    con.close()
    return pd.DataFrame(filas, columns=COLUMNAS_OPERACIONES)


def clientes_deudores():
    """Clientes con al menos una operación con saldo pendiente."""
    df = listar_operaciones()
    if df.empty:
        return df
    deudores = df[(df["deuda_ars"] > 0.005) | (df["deuda_usd"] > 0.005)]
    return (
        deudores.groupby(["cliente", "telefono_wp"], dropna=False)
        .agg(operaciones_pendientes=("id", "count"),
             deuda_ars=("deuda_ars", "sum"),
             deuda_usd=("deuda_usd", "sum"))
        .reset_index()
        .sort_values("deuda_ars", ascending=False)
    )


def _normalizar(texto):
    """Pasa a minúsculas y quita acentos, para que 'lópez' encuentre 'Lopez'."""
    texto = unicodedata.normalize("NFD", str(texto or ""))
    return "".join(c for c in texto if unicodedata.category(c) != "Mn").lower()


def buscar_clientes(texto):
    """Busca por cualquier parte del nombre (apellido incluido) o por número de WhatsApp."""
    clientes = listar_clientes()
    texto = (texto or "").strip()
    if not texto:
        return clientes
    buscado = _normalizar(texto)
    digitos = re.sub(r"\D", "", texto)
    resultado = []
    for c in clientes:
        por_nombre = buscado in _normalizar(c["nombre"])
        por_numero = bool(digitos) and digitos in re.sub(r"\D", "", c["telefono_wp"] or "")
        if por_nombre or por_numero:
            resultado.append(c)
    return resultado


