def _solo_alfanumerico(texto):
    return re.sub(r"[^a-z0-9]", "", _normalizar(texto))


def buscar_productos(texto):
    """Busca por nombre (sin importar mayúsculas ni acentos) o por número de serie (con o sin guiones)."""
    productos = listar_productos()
    texto = (texto or "").strip()
    if not texto:
        return productos
    buscado = _normalizar(texto)
    serie_buscada = _solo_alfanumerico(texto)
    resultado = []
    for p in productos:
        por_nombre = buscado in _normalizar(p["descripcion"])
        por_serie = bool(serie_buscada) and serie_buscada in _solo_alfanumerico(p["numero_serie"] or "")
        if por_nombre or por_serie:
            resultado.append(p)
    return resultado


