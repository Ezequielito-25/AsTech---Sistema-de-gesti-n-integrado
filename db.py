def registrar_operacion(tipo, cliente_id, fecha, descripcion, monto_ars, monto_usd,
                        pagado_ars, pagado_usd, items=None):
    """Crea una venta o reparación. `items` es una lista de dicts para ventas."""
    con = conectar()
    cur = con.execute(
        """INSERT INTO operaciones
           (tipo, cliente_id, fecha, descripcion, monto_ars, monto_usd, pagado_ars, pagado_usd)
           VALUES (?,?,?,?,?,?,?,?) RETURNING id""",
        (tipo, cliente_id, fecha.isoformat(), descripcion, monto_ars, monto_usd, pagado_ars, pagado_usd),
    )
    op_id = cur.fetchone()["id"]
    for it in items or []:
        con.execute(
            """INSERT INTO operacion_items
               (operacion_id, producto_id, descripcion, cantidad, precio_ars, precio_usd)
               VALUES (?,?,?,?,?,?)""",
            (op_id, it.get("producto_id"), it["descripcion"], it["cantidad"],
             it["precio_ars"], it["precio_usd"]),
        )
    con.commit()
    con.close()
    return op_id


