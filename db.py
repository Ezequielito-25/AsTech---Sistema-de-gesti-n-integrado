def eliminar_cliente(cliente_id):
    """Borra el cliente con sus operaciones y renglones. Antes guarda una copia de sus datos en 'clientes_eliminados'."""
    con = conectar()
    cliente = con.execute("SELECT * FROM clientes WHERE id = ?", (cliente_id,)).fetchone()
    if cliente:
        operaciones = con.execute("SELECT * FROM operaciones WHERE cliente_id = ?", (cliente_id,)).fetchall()
        items = con.execute(
            """SELECT i.* FROM operacion_items i
               JOIN operaciones o ON o.id = i.operacion_id WHERE o.cliente_id = ?""",
            (cliente_id,),
        ).fetchall()
        copia = {"cliente": dict(cliente), "operaciones": [dict(o) for o in operaciones],
                 "items": [dict(i) for i in items]}
        con.execute(
            "INSERT INTO clientes_eliminados (cliente_id, nombre, datos, borrado_en) VALUES (?,?,?,?)",
            (cliente_id, cliente["nombre"], json.dumps(copia, default=str, ensure_ascii=False),
             datetime.now().isoformat(timespec="seconds")),
        )
    con.execute("""DELETE FROM operacion_items WHERE operacion_id IN
                   (SELECT id FROM operaciones WHERE cliente_id = ?)""", (cliente_id,))
    con.execute("DELETE FROM operaciones WHERE cliente_id = ?", (cliente_id,))
    con.execute("DELETE FROM clientes WHERE id = ?", (cliente_id,))
    con.commit()
    con.close()


